#!/usr/bin/env python3
"""
Example/test script for the Qdrant Vector Storage & Retrieval Module.

Loads embeddings generated by the embedding module, indexes them into
Qdrant, generates a text query embedding with the same model, and searches
for the top-k most similar frames.

Usage:
    python test_vector_store.py --video-dir processed_videos/my_video --model-type clip
    python test_vector_store.py --video-dir processed_videos/my_video --model-type siglip --top-k 3
"""
import argparse

from embedding import EmbeddingConfig, EmbeddingGenerator
from vector_store import QdrantConfig, index_video_dir, search

SAMPLE_QUERY = "person walking"


def parse_args():
    parser = argparse.ArgumentParser()
    parser.add_argument("--video-dir", type=str, required=True,
                         help="Path to processed_videos/<video_name> (must already contain an embeddings/ folder).")
    parser.add_argument("--model-type", type=str, default="clip", choices=["clip", "siglip"])
    parser.add_argument("--top-k", type=int, default=5)
    return parser.parse_args()


def main():
    args = parse_args()

    qdrant_config = QdrantConfig()

    print(f"\nIndexing embeddings from: {args.video_dir}")
    summary = index_video_dir(args.video_dir, model_type=args.model_type, config=qdrant_config)
    print(f"Indexed {summary['points_indexed']} vectors into collection '{summary['collection']}' "
          f"(dim={summary['embedding_dim']}, model={summary['model_type']})")

    print(f"\nGenerating text embedding for query: '{SAMPLE_QUERY}' (model: {args.model_type})")
    embed_config = EmbeddingConfig(model_type=args.model_type, video_dir=args.video_dir)
    generator = EmbeddingGenerator(embed_config)
    query_vector = generator.embed_query(SAMPLE_QUERY)

    print(f"\nSearching top {args.top_k} result(s)...")
    results = search(query_vector, model_type=args.model_type, top_k=args.top_k, config=qdrant_config)

    print("\n=== Top Results ===")
    if not results:
        print("No results found. Was the collection indexed with the same --model-type?")
    for i, r in enumerate(results, start=1):
        print(
            f"{i}. score={r['score']:.4f}  timestamp={r['timestamp']}  "
            f"frame={r['frame_filename']}  video={r['video_name']}"
        )


if __name__ == "__main__":
    main()
